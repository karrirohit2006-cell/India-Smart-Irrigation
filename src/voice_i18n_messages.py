def get_voice_message(key: str, lang_code: str = "en", **kwargs: Any) -> str:
    """Retrieve localized message for voice assistant speech and display text."""
    code = (lang_code or "en").lower().strip()

    # Localize state name if state keyword is passed
    if "state" in kwargs and code in STATE_LOCALIZED_NAMES:
        state_val = kwargs["state"]
        if state_val in STATE_LOCALIZED_NAMES[code]:
            kwargs["state"] = STATE_LOCALIZED_NAMES[code][state_val]

    msg_dict = VOICE_LOCALIZED_MESSAGES.get(key, {})
    template = msg_dict.get(code) or msg_dict.get("en") or "Action performed."
    try:
        return template.format(**kwargs)
    except Exception:
        return template
