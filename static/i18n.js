/**
 * i18n Engine Helpers
 */
class IrrigationI18n {
    constructor() {
        this.currentLang = this.getStoredLanguage();
    }

    getStoredLanguage() {
        try {
            const saved = localStorage.getItem("preferred_farmer_language");
            if (saved && I18N_DICTIONARY[saved]) return saved;
        } catch (e) {}
        return "en";
    }

    async setLanguage(langCode, persistToServer = true) {
        if (!I18N_DICTIONARY[langCode]) {
            langCode = "en";
        }
        this.currentLang = langCode;
        try {
            localStorage.setItem("preferred_farmer_language", langCode);
        } catch (e) {}

        const langMeta = SUPPORTED_LANGUAGES.find(l => l.code === langCode) || { dir: "ltr" };
        document.documentElement.lang = langCode;
        document.documentElement.dir = langMeta.dir || "ltr";

        // Update all language select elements on page
        document.querySelectorAll("select.lang-selector, select#language, select#onboardLanguageSelect, select#languageSelect").forEach(sel => {
            sel.value = langCode;
        });

        // Translate UI
        this.translatePage(langCode);

        // Optionally persist to server session / farmer profile
        if (persistToServer) {
            try {
                await fetch("/api/farmer/language", {
                    method: "POST",
                    headers: { "Content-Type": "application/json" },
                    body: JSON.stringify({ language: langCode })
                });
            } catch (err) {
                console.warn("Could not sync language with backend:", err);
            }
        }

        window.dispatchEvent(new CustomEvent("farmerLanguageChanged", { detail: { language: langCode } }));
    }

    t(key, fallback = "") {
        const dict = I18N_DICTIONARY[this.currentLang] || I18N_DICTIONARY.en;
        return dict[key] || (I18N_DICTIONARY.en && I18N_DICTIONARY.en[key]) || fallback || key;
    }

    translatePage(langCode = this.currentLang) {
        const dict = I18N_DICTIONARY[langCode] || I18N_DICTIONARY.en;

        // Elements with data-i18n
        document.querySelectorAll("[data-i18n]").forEach(el => {
            const key = el.getAttribute("data-i18n");
            if (dict[key]) {
                if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
                    el.placeholder = dict[key];
                } else {
                    el.textContent = dict[key];
                }
            }
        });

        // Elements with data-i18n-placeholder
        document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
            const key = el.getAttribute("data-i18n-placeholder");
            if (dict[key]) el.placeholder = dict[key];
        });

        // Specific IDs across login, register, onboarding and dashboard
        const idMap = {
            "mainWelcomeHeading": "welcomeHeader",
            "mainTagline": "tagline",
            "mainSubtext": "subtext",
            "loginTitle": "welcomeFarmer",
            "loginSub": "signInToManage",
            "lblUsername": "usernameLabel",
            "lblPassword": "passwordLabel",
            "lblConfirmPassword": "confirmPasswordLabel",
            "btnSignIn": "btnSignIn",
            "btnRegisterSubmit": "btnCreateAccount",
            "btnVoiceGuide": "voiceGuideBtn",
            "btnVoiceMic": "voiceMicBtn",
            "voiceGuideHelpText": "voiceGuideTitle",
            "statLabelTotal": "landTotalLabel",
            "statLabelCultivated": "landCultivatedLabel",
            "statLabelAvailable": "landAvailableLabel",
            "statLabelSections": "landSectionsLabel",
            "btnAddSectionModalBtnSpan": "btnAddSection",
            "onboardTitleText": "onboardingTitle",
            "btnNextStepText": "nextStep",
            "btnPrevStepText": "prevStep",
            "btnSaveOnboardText": "saveOnboarding"
        };

        for (const [id, key] of Object.entries(idMap)) {
            const el = document.getElementById(id);
            if (el && dict[key]) {
                el.textContent = dict[key];
            }
        }
    }

    getPageInstructions(pageType = null) {
        if (!pageType) {
            const path = (window.location && window.location.pathname) ? window.location.pathname.toLowerCase() : "";
            if (path.includes("login") || path === "/") pageType = "login";
            if (path.includes("register")) pageType = "register";
            else if (path.includes("onboarding")) pageType = "onboard";
            else if (path.includes("dashboard") || document.getElementById("landManagementModule") || document.getElementById("sectionFarmOverview")) pageType = "dashboard";
        }
        const dict = I18N_DICTIONARY[this.currentLang] || I18N_DICTIONARY.en;
        if (pageType === "login" || pageType === "register") {
            return dict.pageGuideLogin || dict.voiceWelcomeSpeech || I18N_DICTIONARY.en.pageGuideLogin;
        } else if (pageType === "onboard") {
            return dict.pageGuideOnboard || I18N_DICTIONARY.en.pageGuideOnboard;
        } else if (pageType === "planner") {
            return dict.pageGuidePlanner || I18N_DICTIONARY.en.pageGuidePlanner;
        } else {
            return dict.pageGuideDashboard || dict.voiceWelcomeSpeech || I18N_DICTIONARY.en.pageGuideDashboard;
        }
    }

    populateSelectElements() {
        const selects = document.querySelectorAll("select.lang-selector, select#language, select#onboardLanguageSelect, select#languageSelect");
        selects.forEach(select => {
            if (select.dataset.populated === "true") {
                select.value = this.currentLang;
                return;
            }
            // If select already has pre-rendered options, preserve them!
            if (select.options.length < 5) {
                select.innerHTML = "";
                SUPPORTED_LANGUAGES.forEach(lang => {
                    const opt = document.createElement("option");
                    opt.value = lang.code;
                    opt.textContent = `${lang.nativeName} (${lang.name})`;
                    if (lang.code === this.currentLang) opt.selected = true;
                    select.appendChild(opt);
                });
            } else {
                select.value = this.currentLang;
            }
            select.dataset.populated = "true";

            select.addEventListener("change", (e) => {
                this.setLanguage(e.target.value, true);
            });
        });
    }

    speak(text, langCode = this.currentLang, onEnd = null) {
        if (window.AgriVoiceAudio) {
            window.AgriVoiceAudio.play(text, langCode, onEnd);
            return;
        }

        if (!('speechSynthesis' in window)) {
            console.warn("Speech synthesis not supported in this browser.");
            if (onEnd) onEnd();
            return;
        }

        window.speechSynthesis.cancel();
        const utterance = new SpeechSynthesisUtterance(text);
        const meta = SUPPORTED_LANGUAGES.find(l => l.code === langCode) || { bcp47: "en-IN" };
        utterance.lang = meta.bcp47;
        utterance.rate = 0.95;
        utterance.pitch = 1.0;

        const voices = window.speechSynthesis.getVoices();
        const matchedVoice = voices.find(v => v.lang === meta.bcp47 || v.lang.startsWith(meta.bcp47.split("-")[0]));
        if (matchedVoice) {
            utterance.voice = matchedVoice;
        }

        if (onEnd) {
            utterance.onend = onEnd;
            utterance.onerror = onEnd;
        }

        window.speechSynthesis.speak(utterance);
    }

    playVoiceInstructions(langCode = this.currentLang, onEnd = null) {
        const speech = this.getPageInstructions();
        this.speak(speech, langCode, onEnd);
    }
}

// Global instance
window.AgriI18n = new IrrigationI18n();

// Initialize on DOMContentLoaded
document.addEventListener("DOMContentLoaded", async () => {
    // Check if farmer has preferred language on server
    try {
        const res = await fetch("/api/farmer/language");
        if (res.ok) {
            const data = await res.json();
            if (data && data.language && I18N_DICTIONARY[data.language]) {
                window.AgriI18n.currentLang = data.language;
            }
        }
    } catch (e) {}

    window.AgriI18n.populateSelectElements();
    window.AgriI18n.setLanguage(window.AgriI18n.currentLang, false);
});
